#ejemplo de uso de operadores de aritmetica en python



def aritmetica():
    #suma
    suma = 5+3
    print("suma: 5+3 =",suma)
#resta
    resta = 10-4
    print("resta: 10-4=", resta)
#multiplicacion

    multiplicacion = 6*7
    print("multipliccion: 6*7=", multiplicacion)
#division entera
    division_entera= 10//3
    print("division entera 10//3=", division_entera)
#modulo

    modulo = 10%3
    print("modulo: 10&3=", modulo)
#potenciacion
    potenciacion= 2**3
    print("potenciacion: 2**3=", potenciacion)


def main():
    aritmetica()

if __name__ =="__main__":
    main()
    
